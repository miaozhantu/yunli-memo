const KEYS = Object.keys(MAP).sort(function (a, b) {
  return b.length - a.length;
});

// 去掉「去 / 上 / 第X节」这类前缀，不影响识别但影响截断效果
function clean(title) {
  return String(title || '')
    .replace(/^[去上到]+/, '')
    .replace(/^第[一二三四五六七八九十0-9]+节/, '')
    .trim();
}

function brief(title, max) {
  const limit = max || 6;
  const text = clean(title);
  if (!text) return '待办';

  // 最长命中优先，「高等数学（下）」也能认成高数
  for (let i = 0; i < KEYS.length; i += 1) {
    if (text.indexOf(KEYS[i]) >= 0) return MAP[KEYS[i]];
  }

  return text.length > limit ? text.slice(0, limit) : text;
}

module.exports = { brief, clean };
