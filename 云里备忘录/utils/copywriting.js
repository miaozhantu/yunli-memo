function moodEnabled() {
  return store.config().moodCopy !== false;
}

function allBags() {
  const bags = store.get(BAG_KEY, {});
  return bags && typeof bags === 'object' ? bags : {};
}

// 洗牌袋：抽空之前不重复
function drawIndex(key, length) {
  const bags = allBags();
  let bag = Array.isArray(bags[key]) ? bags[key] : [];

  // 池子改过长度的话，把越界的下标丢掉
  bag = bag.filter(function (i) {
    return typeof i === 'number' && i >= 0 && i < length;
  });

  if (!bag.length) {
    bag = [];
    for (let i = 0; i < length; i += 1) bag.push(i);
    for (let i = bag.length - 1; i > 0; i -= 1) {
      const j = Math.floor(Math.random() * (i + 1));
      const tmp = bag[i];
      bag[i] = bag[j];
      bag[j] = tmp;
    }
  }

  const index = bag.shift();
  bags[key] = bag;
  store.set(BAG_KEY, bags);
  return index;
}

function pick(key) {
  if (!moodEnabled()) {
    if (key.indexOf('cmp') === 0) return '比上月有变化，具体数字在上面。';
    return NEUTRAL[key] || '已完成';
  }

  const pool = POOLS[key] || POOLS.general;
  const index = drawIndex(key, pool.length);
  return pool[index] || pool[0];
}

function greet(hour) {
  const h = typeof hour === 'number' ? hour : new Date().getHours();
  let key = 'greetAfternoon';
  if (h < 6) key = 'greetNight';
  else if (h < 9) key = 'greetDawn';
  else if (h < 11) key = 'greetMorning';
  else if (h < 14) key = 'greetNoon';
  else if (h < 18) key = 'greetAfternoon';
  else if (h < 23) key = 'greetEvening';
  else key = 'greetNight';

  if (!moodEnabled()) return '今天也要好好记一笔';
  return pick(key);
}

function monthly(tagName) {
  if (!moodEnabled()) {
    return '本月最大的支出在「' + (tagName || '其他') + '」。';
  }
  return MONTHLY[tagName] || MONTHLY['其他'];
}

